"""SDK-клиент модели — один конструктор на все классы, которые ходят в модель."""
from openai import OpenAI

# Без явного срока SDK ждёт ответа 600 с и повторяет запрос ещё дважды — до
# получаса на один зависший вызов. Живьём 2026-09-14 (лид #1195): прогон стоял
# больше десяти минут на «Генерирую сообщение...», поток висел в чтении
# TLS-сокета к Google, и соединение сменилось только после шестисот секунд.
# Письмо и ответы на вопросы формы приходят за десятки секунд — 90 с это запас;
# повторы SDK остаются, но каждый теперь короткий.
MODEL_CALL_TIMEOUT_SECONDS = 90.0


def build_openai_client(api_key: str, base_url: str | None = None) -> OpenAI:
    return OpenAI(api_key=api_key, base_url=base_url,
                  timeout=MODEL_CALL_TIMEOUT_SECONDS)
