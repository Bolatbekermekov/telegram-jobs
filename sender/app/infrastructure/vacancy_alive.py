"""Жива ли ещё вакансия — дешёвым GET, ДО того как за письмо заплачено.

Замер прогона 2026-08-26 по площадке `remocate`: из двенадцати лидов четыре
вели на закрытые вакансии, и в логе у каждого сначала шло «Генерирую
сообщение...», а уже потом «страница недоступна / вакансия неактуальна».
Порядок и есть проблема: письмо пишет модель (плюс классификация роли и тема —
три платных вызова), браузер поднимается, и только после этого канал открывает
страницу и обнаруживает, что объявления нет. Треть лидов площадки сжигала
генерацию впустую:

    #414 toughbyte.com/positions/…/full-stack-javascript-developer-3037  — «Closed»
    #416 joom-group.breezy.hr/p/df9b90d18230-…                           — «Position Closed»
    #420 youhodler.com/careers/engineer-frontend                         — 404
    #425 joom.potok.io/open/jobs/7413/closed                             — 404

Проверка сознательно повторяет часть того, что канал потом сделает браузером:
другого способа спросить страницу ДО генерации нет, а цена вопроса — один-два
обычных запроса против трёх вызовов модели и поднятого Chrome. Глубокую работу —
JS, распознавание формы, заполнение — она не трогает вовсе, это по-прежнему дело
канала, и правило «страница мертва» у них одно на двоих (`domain/page_gone.py`).

Отдельным модулем, а не в `vacancy_fetcher`, потому что тот файл побайтово
зеркалит копию интейк-бота (см. tests/test_vacancy_mirror.py): интейку эта
проверка не нужна, а разъехаться копиям нельзя.
"""
from app.domain.page_gone import html_says_gone, redirect_says_gone
from app.domain.vacancy_text import aggregator_apply_url, is_aggregator_job_url
# UA берётся из зеркального модуля, а не копируется сюда: строка там одна и
# объяснена там же («бот-подобный UA придушат hh и LinkedIn»). Второй экземпляр
# той же строки — это второе место, где она может молча устареть. Подчёркивание
# означает «не часть публичной поверхности ТОГО модуля», а не «трогать нельзя».
from app.infrastructure.vacancy_fetcher import _UA

# Сколько ждать страницу. Замер 2026-08-26, 32 чтения обычным GET: страница
# агрегатора 0,74–3,94 с (в среднем 2,0), страница работодателя 0,44–4,56 с
# (в среднем 2,6) плюс один выброс 11,1 с. Восьми секунд хватает на 31 чтение из
# 32; выброс сознательно оставлен таймауту, потому что непрочитанная страница
# считается ЖИВОЙ — ждать дольше значит задерживать лид, который мы всё равно
# отправим. По той же причине нет повторов: повтор удваивает ожидание ради
# ответа, который в неудачном случае ничего не меняет. Отсюда и потолок в две
# страницы на лид: худший случай — 16 секунд, обычный — около трёх.
_TIMEOUT_SECONDS = 8.0

# Чем сайт говорит «этой страницы больше нет». 403 сюда НЕ входит намеренно: это
# «нас не пустили» (Cloudflare, гео-блок, антибот), а не «вакансии нет», и
# похоронить по нему живое объявление — самая дорогая из возможных здесь ошибок.
# По той же логике мимо проходят 429 и любые 5xx: лежит сайт, а не вакансия.
#
# Замер 2026-08-26: из четырнадцати случайных карточек remocate восемь вели на
# 404/410 у работодателя — площадка держит устаревшие объявления, так что код
# ответа ловит даже больше, чем текст страницы.
_GONE_STATUS = (404, 410)


def _read_page(url: str, timeout: float) -> tuple[int, str, str]:
    """(код ответа, разметка, конечный адрес). Код -1 — прочитать не удалось.

    Своя функция, а НЕ `vacancy_fetcher._get_page`: тот сводит 404 и таймаут к
    одному пустому ответу. Для чтения описания это правильно (разбирать нечего в
    обоих случаях), здесь — недопустимо: «страницы нет» и «мы её не прочитали»
    обязаны привести к разным решениям, иначе секундная сетевая заминка хоронит
    живую вакансию.
    """
    import httpx

    try:
        resp = httpx.get(url, headers={"User-Agent": _UA}, timeout=timeout,
                         follow_redirects=True)
    except Exception:  # noqa: BLE001 — таймаут, DNS, обрыв: мы просто не знаем
        return -1, "", ""
    return (resp.status_code, resp.text if resp.status_code == 200 else "",
            str(getattr(resp, "url", "") or url))


def _verdict(url: str, timeout: float, read) -> tuple[str, str]:
    """(адрес, доказавший смерть, — или ""; разметка живой страницы)."""
    status, markup, final_url = read(url, timeout)
    landed = final_url or url
    if status in _GONE_STATUS:
        return landed, ""
    if status != 200:
        return "", ""                 # 403/429/5xx/сеть — вердикта нет
    # Два независимых свидетельства смерти, и второе не стоит ни одного запроса:
    # адрес, на котором мы оказались, читается всё равно. Замер 2026-08-27 на 215
    # ссылках отклика с карточек remocate: разметка ловит 85 мёртвых, а ещё 53
    # отвечают честным 200 и молчат — сайт увёл на заглушку, и виден только
    # редирект. Что считать «увёл», объяснено в `domain/page_gone.py`.
    gone = redirect_says_gone(url, landed) or html_says_gone(markup)
    return (landed if gone else ""), markup


def vacancy_gone(url: str, timeout: float = _TIMEOUT_SECONDS, read=None) -> str:
    """Адрес страницы, доказавшей, что вакансии больше нет, — или "".

    Пустая строка означает «не знаю», а не «жива»: недоступный на секунду сайт,
    403 от антибота, севший DNS — всё это возвращает "", и лид идёт дальше ровно
    как раньше. Так и задумано. Пропущенная мёртвая вакансия стоит одной
    генерации; похороненная живая стоит самой вакансии, и эти цены несравнимы.

    Прыжок за ссылкой отклика делается ТОЛЬКО с агрегатора, и это не экономия
    запроса, а единственный способ увидеть то, что видел прогон: карточка на
    remocate живёт своей жизнью, а умирает страница работодателя за ней — все
    четыре мёртвых лида 2026-08-26 были именно такими. Ссылку ищет тот же
    `aggregator_apply_url`, которым ходит канал, и на тех же условиях: адрес
    берётся с кнопки отклика, а когда её нет и однозначного кандидата тоже —
    прыжка нет, потому что угадывать между чужими работодателями нельзя ни
    здесь, ни там.
    """
    _read = _read_page if read is None else read
    url = (url or "").strip()
    if not url:
        return ""
    try:
        dead, markup = _verdict(url, timeout, _read)
        if dead or not markup or not is_aggregator_job_url(url):
            return dead
        apply_url = aggregator_apply_url(markup, url)
        return _verdict(apply_url, timeout, _read)[0] if apply_url else ""
    except Exception:  # noqa: BLE001 — проверка не обязана стоить прогона: любая
        # неожиданность здесь означает «не знаю», то есть поведение как раньше.
        return ""
