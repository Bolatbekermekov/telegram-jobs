"""Описание вакансии простым HTTP — общий дешёвый путь для скоринга.

Скоринг читает описание каждой найденной вакансии, и до 2026-08-28 читал его
браузером: ~38 с на hh, ~19 с на LinkedIn. Из этих секунд на модель уходит 1-2
(замер gpt-5.4-nano, рассуждающих токенов ноль) — всё остальное было загрузкой
скриптов, стилей и картинок ради одного блока текста. Именно эта цена и держала
потолок MATCH_SCAN_LIMIT на 150: полтора часа на площадку.

Обе площадки отдают описание в серверной разметке и БЕЗ логина. Замеры того же
дня: hh — 14 случайных вакансий подряд без пауз, 14 ответов 200 по 0,60 с,
описание нашлось в 13 (четырнадцатая в архиве — там блока нет и у браузера);
LinkedIn — 6 из 6 за 0,78-1,05 с, с названием компании в придачу.

Читалка не новая: `fetch_vacancy_text` написана для интейк-бота и знает разметку
hh, вакансий и постов LinkedIn, Threads и агрегаторов. Здесь только лёгкая
обёртка вокруг неё — ленивый импорт (чтение страниц живёт в другом слое) и
гарантия, что сбой сети вернёт пусто, а не уронит прогон: за пустотой у обоих
searcher'ов стоит браузер.
"""


def http_vacancy_text(url: str) -> str:
    """Текст вакансии по HTTP, или "" — если адрес незнаком или сеть отвалилась."""
    from app.infrastructure.vacancy_fetcher import fetch_vacancy_text
    try:
        return fetch_vacancy_text(url)
    except Exception:  # noqa: BLE001 — остаётся браузер, ронять прогон незачем
        return ""
