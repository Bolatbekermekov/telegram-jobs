"""Перечитка вакансии: дешёвым HTTP, а браузером — только где HTTP не пройдёт.

Замер 2026-09-11 на лиде #991 (`hh.ru/vacancy/136926142`): обычный GET получает
403, и это антибот hh, а не снятая вакансия — тот же ответ приходит и с `hh.kz`.
Ломалась от этого вся цепочка, и ломалась молча: интейк читает ссылку с
датацентрового IP Vercel и получает 403, поэтому «Вакансия» остаётся пустой;
прогон на ноуте видит пустую колонку, перечитывает ссылку тем же простым HTTP и
получает тот же 403; письмо писать не из чего, и лид возвращается в очередь
каждый прогон навсегда. То есть любая hh-ссылка, присланная боту руками, вставала
намертво.

Браузер эту страницу открывает — у поиска по hh ровно такой запасной ход уже
есть (`HHSearcher.describe`), просто у цикла отправки не было открытой страницы.
И остаётся он именно запасным: замер той же площадки даёт ~38 с на страницу через
браузер против 0.6 с через HTTP.
"""
from app.domain.vacancy_text import is_hh_vacancy_url


def refetch_vacancy(url: str, http_read, browser_read=None) -> str:
    """Текст вакансии по ссылке, или "" если прочитать не удалось.

    `browser_read` зовётся ТОЛЬКО для hh и только после пустого HTTP: у
    остальных площадок пустой ответ значит пустую страницу (Ashby и Workable
    отдают React-шелл без текста), и браузер там не добавит ничего, зато отнимет
    полминуты на каждом таком лиде.
    """
    text = http_read(url)
    if text:
        return text
    if browser_read is None or not is_hh_vacancy_url(url):
        return ""
    try:
        return browser_read(url) or ""
    except Exception:  # noqa: BLE001 — перечитка не обязана удаться, лид ждёт следующего раза
        return ""
