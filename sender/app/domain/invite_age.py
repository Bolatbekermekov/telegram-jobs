"""Срок давности запроса на контакт в LinkedIn. Чистая логика, без похода в лист.

Лид в статусе `invited` не двигается ничем, кроме чужого решения: письмо ему
отправить нельзя, пока он не примет запрос. Поэтому каждый прогон открывает его
профиль заново — и без срока давности делает это бесконечно. На 2026-08-03 в
листе висело 7 таких строк, самая старая (#79) проверялась с 17 июля.

Дата отправки приглашения известна не всегда: `invited_plain` ставил статус
через `mark_status`, а тот колонку «Дата отправки» не трогает, так что все 7
строк остались без даты. Заменить её «Датой добавления» нельзя — замер по 116
отправленным лидам дал разрыв между добавлением и контактом медианой 37 часов и
p90 в 295 часов (12 дней). Поэтому приглашение без даты считается просроченным:
его возраст неизвестен, а «неизвестно» здесь означает «проверяем вечно».
"""
from datetime import datetime, timedelta

# Начало заметки, которую видит человек в листе. По нему же `record_to_sent`
# узнаёт закрытое приглашение среди прочих `skipped`: обращение к человеку
# состоялось, и адрес обязан остаться в истории отправок, иначе защита от
# дублей снова сочтёт его нетронутым.
EXPIRED_NOTE_PREFIX = "LinkedIn: приглашение без ответа"


def invite_expired(sent_at: datetime | None, now: datetime,
                   max_wait_days: int) -> bool:
    """Пора ли перестать проверять это приглашение."""
    if sent_at is None:
        return True
    return now - sent_at >= timedelta(days=max_wait_days)


def expired_note(sent_at: datetime | None, now: datetime,
                 max_wait_days: int) -> str:
    """Почему строка закрыта — так, чтобы человек мог решить сам, слать ли заново."""
    tail = f"перестаю проверять (жду не дольше {max_wait_days} дн.)"
    if sent_at is None:
        return (f"{EXPIRED_NOTE_PREFIX}, дата отправки не записана — {tail}")
    days = (now - sent_at).days
    return (f"{EXPIRED_NOTE_PREFIX} {days} {_days_word(days)} "
            f"(отправлено {sent_at:%Y-%m-%d}) — {tail}")


def _days_word(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return "день"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "дня"
    return "дней"
