"""Заметка об отправке: какое резюме реально ушло. Чистая логика.

Резюме выбирается под роль вакансии — вариантов восемь, — но в листе от этого
не оставалось следа: «Заметка» у отправленных строк пустая, и понять задним
числом, какой из восьми PDF получил рекрутёр, было неоткуда.

Отдельно важен случай, когда файл НЕ уходил: Wellfound принимает только текст,
Threads вложений не поддерживает тоже. Там `attachment_path` заполнен, канал
его молча игнорирует, и запись «CV: …pdf» была бы прямой неправдой — ровно про
то, ради чего заметка и заводится.
"""
from pathlib import PurePath


def cv_note(attachment_path, supported: bool, enabled: bool) -> str:
    """Строка для «Заметки» отправленной строки.

    `supported` — умеет ли канал вкладывать файлы вообще,
    `enabled` — включено ли вложение настройкой ATTACH_CV.

    Из пути берётся только имя файла: путь тянет за собой имя пользователя и
    структуру диска, а лист может быть открыт не только автору.
    """
    if not enabled:
        return "без CV (ATTACH_CV выключен)"
    if not supported:
        return "без CV (канал не поддерживает вложения)"
    name = PurePath(str(attachment_path or "")).name
    if not name:
        return "без CV (файл не выбран)"
    return f"CV: {name}"
