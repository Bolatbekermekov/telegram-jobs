"""На каком языке писать сообщение по вакансии: решаем кодом, а не промптом.

В системном промпте строка «Язык сообщения = язык вакансии» стояла с самого
начала, и она НЕ работает: живая проверка 2026-08-01 на английской вакансии
(Senior Backend Engineer, Go) вернула и письмо, и записку по-русски. Причина
очевидна: весь промпт и весь PROFILE написаны по-русски, и одна строка среди
трёх десятков русских правил проигрывает языку самого промпта.

Поэтому язык определяется здесь, а в промпт уходит уже готовое указание.
"""
import re

_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")
_LETTER = re.compile(r"[^\W\d_]", re.UNICODE)

# Оценка релевантности, которую поиск приклеивает к тексту вакансии
# («70/100: Подходит по стеку и remote»). Она ВСЕГДА по-русски и о языке самой
# вакансии не говорит ничего: из-за неё лид 13 (английская вакансия на
# wellfound) получил русское письмо.
_SCORE_NOTE = re.compile(r"\d{1,3}/100:.*", re.S)

# Порог намеренно несимметричный: спрашиваем ДОЛЮ кириллицы, а не большинство.
# Русское объявление почти всегда набито английскими терминами («Стек: Go,
# PostgreSQL, Kubernetes»), и по простому большинству букв уехало бы в
# английский. Английское объявление кириллицы не содержит почти совсем: доля в
# 15% отделяет русский текст со стеком (обычно за 50%) от английского, в
# котором кириллицей написано имя рекрутёра или город (единицы процентов).
_MIN_CYRILLIC_SHARE = 0.15


def detect_language(vacancy_context) -> str:
    """"ru" или "en" по тексту вакансии.

    Английский это ещё и ответ для всего остального: на пост на фарси (лид 181)
    мы пишем по-английски, а не делаем вид, что знаем фарси. А вот пустой текст
    это не английский, а отсутствие сигнала: поток у нас в основном
    русскоязычный, и без данных остаёмся на русском.
    """
    text = _SCORE_NOTE.sub("", (vacancy_context or "").strip())
    letters = len(_LETTER.findall(text))
    if not letters:
        return "ru"
    return "ru" if len(_CYRILLIC.findall(text)) / letters >= _MIN_CYRILLIC_SHARE else "en"


def language_rule(lang: str) -> str:
    """Добавка к системному промпту, называющая язык прямо.

    Для английского указание продублировано ПО-АНГЛИЙСКИ: модель тянется к
    языку инструкции, и английская фраза в конце русского промпта работает
    сильнее, чем описание того же по-русски.
    """
    if lang == "en":
        return (" ВАЖНО: вакансия на английском, поэтому и всё сообщение пиши "
                "ПО-АНГЛИЙСКИ, без единого русского слова. "
                "IMPORTANT: the job posting is in English. Write the entire "
                "message in English.")
    return " ВАЖНО: вакансия на русском, поэтому и сообщение пиши по-русски."
