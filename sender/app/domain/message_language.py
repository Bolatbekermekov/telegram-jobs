"""На каком языке писать сообщение по вакансии: решаем кодом, а не промптом.

В системном промпте строка «Язык сообщения = язык вакансии» стояла с самого
начала, и она НЕ работает: живая проверка 2026-08-01 на английской вакансии
(Senior Backend Engineer, Go) вернула и письмо, и записку по-русски. Причина
очевидна: весь промпт и весь PROFILE написаны по-русски, и одна строка среди
трёх десятков русских правил проигрывает языку самого промпта.

Поэтому язык определяется здесь, а в промпт уходит уже готовое указание.
"""
import re

_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")
_LETTER = re.compile(r"[^\W\d_]", re.UNICODE)

# Оценка релевантности, которую поиск приклеивает к тексту вакансии
# («70/100: Подходит по стеку и remote»). Она ВСЕГДА по-русски и о языке самой
# вакансии не говорит ничего: из-за неё лид 13 (английская вакансия на
# wellfound) получил русское письмо.
_SCORE_NOTE = re.compile(r"\d{1,3}/100:.*", re.S)

# Подписи, которыми МЫ размечаем текст вакансии, — та же болезнь, что и оценка.
# Пишутся они в трёх местах:
#   «Зарплата: …», «Локация: …»  — search_leads_repo._vacancy_text
#   «Компания: …»                — vacancy_text.extract_linkedin_vacancy
#   «Зарплата: …»                — vacancy_text.extract_hh_vacancy
#
# Выбрасывается СТРОКА ЦЕЛИКОМ, а не одно слово подписи, и это не лишняя
# строгость. У локации от LinkedIn кириллица сидит в ЗНАЧЕНИИ: площадка отдаёт
# её на языке нашей сессии, а сессия русская. Лид #348 приехал как
# «Локация: Европа, Ближний Восток и Африка (Удаленная работа)» при английской
# вакансии Backend Engineer | Remote — Crossing Hurdles. Замер 2026-08-26 по 492
# строкам листа: если убрать только слово подписи, из 14 испорченных лидов не
# чинится НИ ОДИН, а если строку целиком — чинятся все 14.
#
# Из таблицы подписи при этом никуда не деваются: их читает человек, и локация —
# ровно то, по чему он глазами отбирает строки. Они просто не голосуют за язык.
#
# Привязка к началу строки обязательна: «Наша Локация: смотри ниже» посреди
# объявления — это слово работодателя, а не наша разметка.
_OWN_LABEL_LINE = re.compile(r"^(?:Зарплата|Локация|Компания):.*$", re.MULTILINE)


def _employer_words(text) -> str:
    """Текст без наших приписок — только то, что написал работодатель.

    Одна функция на оба места, где текст оценивают (`detect_language` и порог
    доверия в `language_source`): разъехавшись, они начали бы считать язык и
    длину по разным текстам.
    """
    return _OWN_LABEL_LINE.sub("", _SCORE_NOTE.sub("", (text or "").strip()))


# Порог намеренно несимметричный: спрашиваем ДОЛЮ кириллицы, а не большинство.
# Русское объявление почти всегда набито английскими терминами («Стек: Go,
# PostgreSQL, Kubernetes»), и по простому большинству букв уехало бы в
# английский. Английское объявление кириллицы не содержит почти совсем: доля в
# 15% отделяет русский текст со стеком (обычно за 50%) от английского, в
# котором кириллицей написано имя рекрутёра или город (единицы процентов).
_MIN_CYRILLIC_SHARE = 0.15


def detect_language(vacancy_context) -> str:
    """"ru" или "en" по тексту вакансии.

    Английский это ещё и ответ для всего остального: на пост на фарси (лид 181)
    мы пишем по-английски, а не делаем вид, что знаем фарси. А вот пустой текст
    это не английский, а отсутствие сигнала: поток у нас в основном
    русскоязычный, и без данных остаёмся на русском.
    """
    text = _employer_words(vacancy_context)
    letters = len(_LETTER.findall(text))
    if not letters:
        return "ru"
    return "ru" if len(_CYRILLIC.findall(text)) / letters >= _MIN_CYRILLIC_SHARE else "en"


def language_rule(lang: str) -> str:
    """Добавка к системному промпту, называющая язык прямо.

    Для английского указание продублировано ПО-АНГЛИЙСКИ: модель тянется к
    языку инструкции, и английская фраза в конце русского промпта работает
    сильнее, чем описание того же по-русски.
    """
    if lang == "en":
        return (" ВАЖНО: вакансия на английском, поэтому и всё сообщение пиши "
                "ПО-АНГЛИЙСКИ, без единого русского слова. "
                "IMPORTANT: the job posting is in English. Write the entire "
                "message in English.")
    return " ВАЖНО: вакансия на русском, поэтому и сообщение пиши по-русски."


# Сколько букв нужно оригиналу, чтобы ему верили. «React dev» или «Frontend
# Engineer» — это название роли: оно пишется латиницей на любом языке и языка
# не доказывает. Порог низкий намеренно: задача не угадать язык по обрывку, а
# отличить настоящий текст вакансии от ссылки и от пары слов.
_MIN_LETTERS_TO_TRUST = 40


def language_source(lead) -> str:
    """Текст, по которому определяется язык письма: слова РАБОТОДАТЕЛЯ.

    Раньше язык брали из `vacancy_context or raw_text` — то есть из НАШЕГО
    пересказа, а он всегда русский: интейк суммирует русским промптом и
    сохранить язык оригинала не просит (замер 2026-08-26: 35 английских
    вакансий из 35 получили русское описание). Из-за этого письмо в Booking.com
    в Амстердаме уходило бы по-русски, а лиду #441 — стажировке в Бангалоре —
    уже ушло: отклик подан через Easy Apply русским текстом.

    Поэтому порядок обратный: сначала оригинал. Пересказ остаётся запасным
    вариантом, и он обязателен — у hh-строки в «Исходном тексте» лежит одна
    ссылка, а у search-лида оба поля совпадают.

    Возвращается ТЕКСТ, а не язык: тот же текст нужен и подписи, и правилу для
    модели, и разъехаться они не должны.
    """
    raw = _employer_words(getattr(lead, "raw_text", ""))
    if len(_LETTER.findall(raw)) >= _MIN_LETTERS_TO_TRUST:
        return getattr(lead, "raw_text", "") or ""
    return (getattr(lead, "vacancy_context", "") or ""
            or getattr(lead, "raw_text", "") or "")


# Площадки, у которых язык вакансии известен без чтения текста.
#
# hh.ru — русскоязычный сайт: и объявления, и переписка на нём по-русски. Замер
# 2026-08-26 по всем 106 hh-строкам листа не нашёл ни одной англоязычной
# вакансии. А определять этот язык ПО ТЕКСТУ у hh не по чему, и держался он до
# сих пор на случайностях:
#
# * search-лид площадки хранит заголовок, компанию и нашу же строку локации.
#   «QA Engineer Middle (mobile) — Gaijin Games, Локация: Serbia» (#466)
#   считался русским ровно из-за слова «Локация»: 15.2% кириллицы при пороге
#   15%. Стоит перестать считать НАШИ подписи — и 22 русские вакансии hh
#   получают английские письма;
# * у лида из телеграма в «Исходном тексте» лежит ссылка, и её слов
#   (`hhtmFromLabel`, `suitable_vacancies`, `utm_source`) хватает, чтобы порог
#   доверия сработал и вакансия прочиталась как английская. Так уже происходит
#   с 17 строками — #55, #101, #168, #200 и другими: русская вакансия, русский
#   пересказ в таблице, английское письмо. Ещё 5 (#41, #44, #462, #464, #465)
#   уезжают в английский по одному латинскому заголовку.
#
# Поэтому площадка отвечает за свой язык сама, а текст спрашивают только там,
# где он о чём-то говорит.
_RUSSIAN_LANGUAGE_PLATFORMS = frozenset({"hh"})


def language_for(lead) -> str:
    """Язык письма по лиду: одноязычная площадка отвечает за себя сама."""
    platform = (getattr(lead, "platform", "") or "").strip().lower()
    if platform in _RUSSIAN_LANGUAGE_PLATFORMS:
        return "ru"
    return detect_language(language_source(lead))
