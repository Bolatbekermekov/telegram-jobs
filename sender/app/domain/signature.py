"""Подпись под письмом на языке самого письма. Чистая логика.

Подпись не пишет модель: это фиксированный блок из sender/signature.txt, и
клеится он уже ПОСЛЕ генерации. Значит language_rule на него не действует —
английское письмо уезжало с русским «С уважением, Bolatbek» в конце, и
получатель видел единственное русское слово в остальном безупречно английском
тексте.

Меняется ровно строка прощания. Контакты — «Telegram:», «Email:», «LinkedIn:» —
одинаковы в обоих языках, а любая правка адреса или ссылки это опечатка в том
самом контакте, по которому с человеком должны связаться.
"""
import re

# Русское прощание в начале подписи. Запятая необязательна: строку пишет
# человек в своём файле, и «С уважением Bolatbek» встречается не реже.
_RU_SIGN_OFF = re.compile(r"^\s*с\s+уважением\s*,?\s*(?P<name>.*)$", re.I)

_EN_SIGN_OFF = "Best regards"


def localize_signature(signature_text, lang: str) -> str:
    """Подпись, пригодная для письма на языке `lang`.

    Незнакомая формулировка остаётся как есть: угадывать, где тут имя, значит
    рисковать потерять строку или подставить не то. Пусть лучше подпись
    останется прежней, чем станет неправильной.
    """
    text = str(signature_text or "").strip()
    if not text or lang != "en":
        return text
    head, sep, rest = text.partition("\n")
    m = _RU_SIGN_OFF.match(head)
    if not m:
        return text
    name = m.group("name").strip()
    head = f"{_EN_SIGN_OFF}, {name}" if name else _EN_SIGN_OFF
    return head + sep + rest
