"""Живая ли сессия Jobicy. Судим по КУКАМ, а не по разметке.

Первая попытка судила по странице — «нет ссылки на /sign-in, значит мы внутри» —
и немедленно дала ложное «залогинен» прямо на самой странице входа: ссылки на неё
саму там, естественно, нет. Сохранилась гостевая сессия: три куки, одна Cloudflare
и две аналитики Matomo, ни одной авторизационной (замер 2026-09-11).

Разметка для этого не годится в принципе: на гостевой главной Jobicy стоит
`href="/dashboard-page"`, то есть ссылка на личный кабинет видна и тому, кто не
вошёл. Кука — положительное доказательство, и её отсутствие обязано читаться как
«не вошёл»: сохранить гостя дороже, чем попросить войти ещё раз. Та же
дисциплина, что в remoteok_session.py, только признак надёжнее.

Имя куки взято не из головы: Jobicy стоит на WordPress, а тот держит вход в
`wordpress_logged_in_<хеш>`. Если площадка переедет на другой механизм, вход
честно не опознается — и команда покажет `auth_cookie_names`, то есть что реально
пришло. Тогда правка будет по замеру, а не по догадке.
"""
import re

_AUTH_COOKIE_RE = re.compile(r"^wordpress_(?:logged_in|sec)_", re.IGNORECASE)


def auth_cookie_names(cookies) -> list[str]:
    """Имена кук, как их отдал браузер — чтобы показать человеку при неудаче."""
    return [str(c.get("name", "")) for c in (cookies or []) if c.get("name")]


def is_logged_in(cookies) -> bool:
    return any(_AUTH_COOKIE_RE.match(name) for name in auth_cookie_names(cookies))
