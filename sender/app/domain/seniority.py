"""Слово уровня (junior/middle/senior) не должно попадать в исходящий текст.

Запрет «не называй уровень кандидата» в системном промпте держит только одну
половину: модель перестала писать «как senior-разработчик», но продолжила
переписывать в письмо ЗАГОЛОВОК вакансии целиком — «откликаюсь на вакансию
Senior Go Developer», «позиция Middle QA Engineer». Для читателя разницы нет:
в письме стоит уровень, и дальше разговор идёт про него, а не про опыт.

Поэтому правило продублировано здесь, после генерации, как и запрет тире
(`_strip_dashes`): промпт это просьба, а сетка — гарантия. Убирается ровно
слово уровня, остальной текст не трогается: «Senior Go Developer» становится
«Go Developer», а не «разработчик».

Сознательно НЕ трогаем «lead/тимлид/ведущий»: это про роль (кем человек будет
работать), а не про грейд, и вырезать его из «Lead Golang Developer» значит
переписать название должности. Список слов ниже — то, что просили убрать.
"""
import re

# Порядок для наглядности (длинные формы сверху); на разбор он не влияет —
# `(?![\w])` в `_ONE` и так не даёт «джун» съесть начало «джуниора».
_LEVEL_WORDS = (
    "mid-level", "mid level", "entry-level", "entry level",
    "джуниор", "миддл", "сеньор", "синьор", "сениор", "мидл", "джун",
    "junior", "middle", "senior",
    r"jr\.?", r"sr\.?",
)
_LEVEL = "|".join(_LEVEL_WORDS)
_ONE = rf"(?:{_LEVEL})(?![\w])"

# Одно слово уровня или связка из них: «Middle+», «Senior/Middle»,
# «senior level», «mid-level». Хвост `\+?` берёт плюс после слова, иначе от
# «Middle+» осталось бы висящее «+».
_RUN = rf"{_ONE}(?:\s*[/+]\s*{_ONE})*\+?(?:[ \-]level(?![\w]))?"

# Слово уровня редко стоит в тексте голым: вокруг него «уровня», «грейд», «как».
# Эти обёртки убираются вместе с ним и ПЕРВЫМИ, иначе от вырезанного грейда
# остаётся обрубок («мой опыт соответствует уровню.», «расти до -уровня») —
# сломанная фраза в письме заметнее самого слова.
_GRADE_WORD = r"(?:уровн|грейд)\w*"
_GRADE_RE = re.compile(
    rf"\b(?:до|на|в|с)\s+{_GRADE_WORD}\s+(?:{_RUN})"            # «на уровне senior»
    rf"|\b{_GRADE_WORD}\s+(?:{_RUN})"                           # «уровня senior»
    rf"|\b(?:до|на|в|с)\s+(?:{_RUN})\s*[-\s]\s*{_GRADE_WORD}"   # «до senior-уровня»
    rf"|\b(?:{_RUN})\s*[-\s]\s*{_GRADE_WORD}",                  # «middle-грейда»
    re.IGNORECASE)

# «работаю как senior.» — «как» без грейда после него теряет смысл. Только в
# конце оборота: в «как Senior Go Developer» роль остаётся, уходит одно слово.
_TRAILING_RE = re.compile(
    rf"\s*\b(?:как|as\s+an?)\s+(?:{_RUN})(?=\s*(?:[.,;:!?)»]|$))",
    re.IGNORECASE | re.MULTILINE)

_LEVEL_RE = re.compile(rf"\b(?:{_RUN})", re.IGNORECASE)


def _tidy(text: str) -> str:
    """Прибрать шов, оставшийся от вырезанного слова.

    Пробелы схлопываются, опустевшие скобки и сдвоенные запятые убираются,
    пустая строка между абзацами остаётся: `[ \\t]` намеренно не включает
    перевод строки, иначе письмо слиплось бы в стену текста.
    """
    text = re.sub(r"\(\s*\)|«\s*»", "", text)
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"(?:,[ \t]*){2,}", ", ", text)
    text = re.sub(r"[ \t]+([,.;:!?)»])", r"\1", text)
    text = re.sub(r"([(«])[ \t]+", r"\1", text)
    text = re.sub(r"[ \t]+$", "", text, flags=re.MULTILINE)
    text = re.sub(r"^[ \t]+", "", text, flags=re.MULTILINE)
    return text.strip()


def strip_seniority(text: str) -> str:
    """Текст без слов уровня. Всё остальное остаётся как было.

    Порядок правил: сначала обороты вокруг грейда (иначе от них останутся
    обрубки), потом голое слово.
    """
    if not text:
        return text
    out = _TRAILING_RE.sub("", text)
    out = _GRADE_RE.sub(" ", out)
    out = _LEVEL_RE.sub(" ", out)
    return _tidy(out)
