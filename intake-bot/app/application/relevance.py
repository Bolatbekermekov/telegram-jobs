"""Насколько вакансия подходит профилю поиска: промпт и разбор ответа модели.

Копия ноутбучной `sender/app/application/relevance.py` — по той же причине, по
которой скопированы `contact.py`, `lead.py` и `sheets_repo.py`: две половины
проекта деплоятся отдельно (эта — в Vercel), друг друга не импортируют и общего
пакета не имеют. Промпт скопирован ДОСЛОВНО намеренно: оценка пересланной
вакансии и оценка найденной поиском попадают в одну таблицу, и разойдись
формулировки — цифры в соседних строках перестали бы значить одно и то же.

Скопирована только «оценить», без «отфильтровать»: `score_and_filter` здесь не
нужен и не нужен принципиально. Постоянное указание владельца — никогда не
пропускать вакансию молча; интейк оценку РАССКАЗЫВАЕТ, а лид сохраняет всегда.

Одно намеренное расхождение: `parse_score_response` возвращает None вместо
нуля, см. её докстроку.
"""
import json
import re

# Правила отбора стоят ЗДЕСЬ, хотя половина из них уже написана в профиле, и это
# не дублирование от небрежности. Профиль едет ПОЛЬЗОВАТЕЛЬСКИМ сообщением и
# проигрывает системному: прежний промпт говорил «Будь строгим: не та роль или
# уровень выше Junior+ — низкий балл», и выигрывал он, а не профиль, где прямым
# текстом стоят «Middle — ПОДХОДИТ» и «Не снижай оценку за то, что вакансия не
# удалённая».
#
# Замер 2026-08-27/28 на живых карточках remocate, дешёвая модель, порог 60.
# Оценка недетерминирована (temperature не задана), поэтому мерилось не одним
# числом: 38 прогонов на старом промпте и 22 на новом. Отклик на #415 и #422
# прогон КОГДА-ТО ОТПРАВИЛ, а старый промпт их сегодня не пропускает:
#                                             было (n=38)            стало (n=22)
#   #415 Graduate SWE, Bending Spoons       0..78 мед.50  14/38   62..80 мед.76  22/22
#   #418 QA Engineer, Profitap             34..64 мед.52  11/38   62..80 мед.73  22/22
#   #422 QA Engineer (Mid/Senior), Monetha 18..38 мед.35   0/38   68..80 мед.72  22/22
# (Ноль у #415 — не вердикт, а неразобранный ответ; в прогоне он значит ровно то
# же самое, `parse_score_response` отдаёт 0 и вакансия списывается навсегда.)
# Что писала модель в reason, по убыванию частоты: «уровень Mid/Senior, у профиля
# выше Junior+» (это говорил САМ промпт), «требуется 3+ года» как дисквалификация
# (профиль про стаж молчит), «нет опыта сетевого тестирования / Robot Framework»
# (профиль перечисляет, что владелец ИЩЕТ, а не весь его опыт), «гео/удалёнка не
# ясна» (прямой запрет в профиле не сработал).
#
# Отсюда три решения, каждое проверено тем же замером:
#  * второго списка ПОДХОДЯЩИХ уровней в промпте нет — он есть только в профиле
#    (список дисквалифицирующих есть, но он списан с самого профиля);
#  * «будь строгим» заменено ШКАЛОЙ. Одного запрета «не снижай за X» не хватило,
#    и это проверено дважды: запрет абзацем оставил #422 на медиане 35, запрет
#    списком поднял до 45..82 — всё ещё монетка при пороге 60. Шкала называет,
#    за что балл ставится, и разброс схлопывается: #422 стал 68..80;
#  * общая инженерная роль засчитывается за перечисленные в профиле. Без этой
#    строки #415 («Graduate software engineer» — такой роли в профиле дословно
#    нет) держался на медиане 58, то есть ровно на пороге.
#
# Фильтр при этом не превратился в решето — контроли из той же ленты остались
# внизу и ни разу не прошли порог: Senior Full-Stack PHP 10..28, Principal SWE
# 10..20, Senior ML 10..25, Instructional Designer (роль не из профиля) 0..15.
_SCORE_SYSTEM = (
    "Ты оцениваешь, насколько вакансия подходит кандидату по его профилю поиска.\n"
    "Верни ТОЛЬКО JSON: {\"score\": <целое 0-100>, \"reason\": \"<кратко, до 120 символов>\"}.\n"
    "\n"
    "Шкала (список подходящих ролей и уровней берётся ТОЛЬКО из профиля):\n"
    "- роль из профиля И уровень из профиля -> 70-95;\n"
    "- роль из профиля, уровень не назван или назван диапазоном («Mid/Senior»), "
    "в котором есть уровень из профиля -> 65-85;\n"
    "- роль из профиля, но уровень выше (senior / lead / staff / principal / head) -> 10-30;\n"
    "- роль не из профиля -> 0-20;\n"
    "- заявку физически нельзя подать по причине, прямо названной в профиле -> 0-15.\n"
    "\n"
    "Роль засчитывается и тогда, когда она названа общее, чем в профиле: общая "
    "инженерная роль («Software Engineer», «Developer») покрывает перечисленные "
    "в профиле роли разработки.\n"
    "\n"
    "Что балл НЕ снижает (вычитать за это нельзя):\n"
    "- требуемый стаж в годах («3+ years», «5+ лет») — это не уровень;\n"
    "- формат работы: офис, гибрид, не удалённо — подходит любой;\n"
    "- страна вакансии сама по себе: другая страна, релокация, отсутствие "
    "Казахстана в списке стран;\n"
    "- требования, которых в профиле нет (домен, инструмент, фреймворк) — профиль "
    "перечисляет, что кандидат ИЩЕТ, а не весь его опыт.\n"
    "\n"
    "Внутри диапазона шкалы двигай балл только по совпадению стека — не больше чем на 15."
)


def build_score_prompt(profile: str, title: str, description: str,
                       location: str = "") -> tuple[str, str]:
    """Системное сообщение + пользовательское для одной вакансии.

    Локация идёт отдельной строкой, а не внутри описания: страну знает карточка
    выдачи, и у remocate она заполнена всегда («🇩🇪 Germany», «🌎 World»), тогда
    как в тексте объявления её может не быть вовсе. Без неё полстраницы профиля
    про право на работу и спонсорство визы применялись вслепую.

    Пустая локация не оставляет после себя подписи. «Локация: » — не пустое
    место, а факт: модель читает его как «страна не указана» ровно так же, как
    прочитала бы «Зарплата: » (та же причина, что в `_vacancy_text`). Пробелы и
    переводы строк считаются пустотой и схлопываются: hh отдаёт локацию через
    `inner_text` адресного блока карточки, а он бывает многострочным.
    """
    where = " ".join((location or "").split())
    head = "\n".join(p for p in (f"Название: {title}",
                                 f"Локация: {where}" if where else "") if p)
    user = (
        f"=== ПРОФИЛЬ ПОИСКА ===\n{profile}\n\n"
        f"=== ВАКАНСИЯ ===\n{head}\n\n{description}\n\n"
        "Верни только JSON."
    )
    return _SCORE_SYSTEM, user


def parse_score_response(raw: str) -> tuple[int, str] | None:
    """(оценка 0-100, причина) — или None, если ответ разобрать не удалось.

    Здесь и расходятся две копии. На ноуте мусорный ответ превращается в 0, и
    это безопасно: ноль там значит «отбросить», цена ошибки — одна вакансия из
    выдачи, о которой никто ничего не обещал.

    В интейке оценка ложится в «Заметку» и уходит владельцу в ответ бота, то
    есть ЧИТАЕТСЯ КАК ВЕРДИКТ. «0/100» на вакансию, о которой модель на самом
    деле ничего не сказала, — это выдуманный приговор ровно того сорта, от
    которого оценка и заводилась (только наоборот). Не разобрали — оценки нет.
    """
    m = re.search(r"\{.*\}", raw or "", re.DOTALL)
    if not m:
        return None
    try:
        data = json.loads(m.group(0))
        score = int(data["score"])
    except Exception:  # noqa: BLE001 — кривой ответ модели ≠ вердикт о вакансии
        return None
    return max(0, min(100, score)), str(data.get("reason", "")).strip()
