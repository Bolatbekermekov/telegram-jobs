"""На каком языке писать про вакансию: решаем кодом, а не промптом.

Копия ноутбучной `sender/app/domain/message_language.py` — по той же причине,
по которой скопированы `contact.py`, `lead.py` и `relevance.py`: две половины
проекта деплоятся отдельно (эта — в Vercel), друг друга не импортируют и общего
пакета не имеют.

`detect_language` перенесена ДОСЛОВНО, вместе с порогом и объяснением. По ней
ноут выбирает язык письма, а здесь — язык пересказа; разойдись эти двое, и
письмо поехало бы не на том языке, на котором написана колонка «Вакансия».

Не перенесена `language_source`: она выбирает между оригиналом и пересказом, а
здесь пересказ ещё только пишется — оригинал тут единственный текст, какой
есть. Вместо неё `summary_language`, у которой свой вопрос: хватает ли в
оригинале слов, чтобы вообще называть язык.

Расхождение одно и намеренное: `language_rule` на ноуте говорит про ПИСЬМО, а
здесь речь про пересказ, поэтому это отдельная функция с отдельным текстом.
Приём в ней тот же самый, измеренный там же.
"""
import re

from app.domain.vacancy_text import is_link_only

_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")
_LETTER = re.compile(r"[^\W\d_]", re.UNICODE)

# Оценка релевантности, которую поиск приклеивает к тексту вакансии
# («70/100: Подходит по стеку и remote»). Она ВСЕГДА по-русски и о языке самой
# вакансии не говорит ничего: из-за неё лид 13 (английская вакансия на
# wellfound) получил русское письмо.
_SCORE_NOTE = re.compile(r"\d{1,3}/100:.*", re.S)

# Порог намеренно несимметричный: спрашиваем ДОЛЮ кириллицы, а не большинство.
# Русское объявление почти всегда набито английскими терминами («Стек: Go,
# PostgreSQL, Kubernetes»), и по простому большинству букв уехало бы в
# английский. Английское объявление кириллицы не содержит почти совсем: доля в
# 15% отделяет русский текст со стеком (обычно за 50%) от английского, в
# котором кириллицей написано имя рекрутёра или город (единицы процентов).
_MIN_CYRILLIC_SHARE = 0.15


def detect_language(vacancy_context) -> str:
    """"ru" или "en" по тексту вакансии.

    Английский это ещё и ответ для всего остального: на пост на фарси (лид 181)
    мы пишем по-английски, а не делаем вид, что знаем фарси. А вот пустой текст
    это не английский, а отсутствие сигнала: поток у нас в основном
    русскоязычный, и без данных остаёмся на русском.
    """
    text = _SCORE_NOTE.sub("", (vacancy_context or "").strip())
    letters = len(_LETTER.findall(text))
    if not letters:
        return "ru"
    return "ru" if len(_CYRILLIC.findall(text)) / letters >= _MIN_CYRILLIC_SHARE else "en"


def summary_language(source_text) -> str:
    """"ru" / "en" — на каком языке писать пересказ; "" — определять не на чем.

    Три состояния, а не два, потому что сюда приходит СООБЩЕНИЕ как есть, а не
    текст вакансии. Голый адрес `linkedin.com/jobs/view/senior-backend-engineer`
    состоит из трёх десятков латинских букв и по буквам неотличим от английского
    объявления; пересланные два слова («React dev, пиши @ivan») — это название
    роли, оно пишется латиницей на любом языке. Назвать по ним язык значит его
    выдумать, а выдуманный язык здесь дороже неизвестного: колонка «Вакансия»
    это то, из чего ноут пишет письмо, и по ней же он определяет язык, когда
    оригинала не хватает (см. `language_source` в его копии этого файла).

    Порог не свой: `is_link_only` уже отвечает на этот самый вопрос — осталось
    ли в сообщении, кроме ссылок, достаточно слов, чтобы их пересказывать.
    Настроен он на живых сообщениях (одна строка в 91 символ считается
    текстом), и заводить рядом второй порог значило бы развести их со временем.
    """
    if is_link_only(source_text or ""):
        return ""
    return detect_language(source_text)


def summary_language_rule(lang: str) -> str:
    """Добавка к системному промпту суммаризатора, называющая язык прямо.

    Для английского указание продублировано ПО-АНГЛИЙСКИ: модель тянется к
    языку инструкции, и английская фраза в конце русского промпта работает
    сильнее, чем описание того же по-русски. Наблюдение не новое — на письме
    оно измерено 2026-08-01 (см. `language_rule` в ноутбучной копии), а на
    пересказе видно на масштабе: промпт целиком русский, требования сохранить
    язык оригинала в нём не было, и все 35 английских вакансий из листа за
    2026-08-26 получили русское описание.

    Пустой `lang` — «языка не знаем» — не добавляет НИЧЕГО. Написать «пиши
    по-русски» над двумя английскими словами значит заказать перевод и выдать
    догадку за решение; молчание оставляет всё как было — промпт русский,
    пересказ выйдет русским. Это тот же ответ, который на бессигнальном тексте
    даёт ноут (`detect_language("") == "ru"`), так что колонка и письмо
    остаются согласованы.
    """
    if lang == "en":
        return (" ВАЖНО: вакансия написана по-английски, поэтому и пересказ пиши "
                "ПО-АНГЛИЙСКИ, без единого русского слова. "
                "IMPORTANT: the job posting is in English. Write the "
                "vacancy_context value in English.")
    if lang == "ru":
        return " ВАЖНО: вакансия написана по-русски, поэтому и пересказ пиши по-русски."
    return ""
